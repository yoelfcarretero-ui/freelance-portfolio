/**
 * Build step for demo mode: reads data/docs, chunks every document and writes a
 * BM25 index as a TypeScript module that gets bundled into the serverless function.
 *
 *   npm run build:index
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildBm25Index } from "../lib/bm25.js";
import { chunkDocument } from "../lib/chunking.js";
import { loadDocs } from "../lib/docs.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = path.join(root, "data", "docs");
const outFile = path.join(root, "lib", "generated", "bm25-index.ts");

const docs = loadDocs(docsDir);
const chunks = docs.flatMap((doc) => chunkDocument(doc, { maxChars: 900, overlap: 150 }));
const index = buildBm25Index(chunks);

const source = `// AUTO-GENERATED by scripts/build-index.ts - do not edit by hand.
// Source: data/docs/**/*.md (${docs.length} documents, ${chunks.length} chunks)
import type { Bm25Index } from "../bm25.js";

export const bm25Index: Bm25Index = ${JSON.stringify(index)};
`;
writeFileSync(outFile, source, "utf8");

const byLang = chunks.reduce<Record<string, number>>((acc, c) => ((acc[c.lang] = (acc[c.lang] ?? 0) + 1), acc), {});
console.log(
  `BM25 index: ${docs.length} docs, ${chunks.length} chunks (${Object.entries(byLang)
    .map(([l, n]) => `${l}: ${n}`)
    .join(", ")}), ${Object.keys(index.df).length} terms -> ${path.relative(root, outFile)}`,
);
