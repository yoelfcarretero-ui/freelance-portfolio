import { countBySeverity, SEVERITIES, SEVERITY_LABEL, type AuditResult, type Finding } from '../types.js';

const CATEGORY_LABEL: Record<Finding['category'], string> = {
  database: 'Database / RLS',
  rpc: 'RPC functions',
  storage: 'Storage',
  auth: 'Authentication',
  secrets: 'Secrets in code',
  tool: 'Tool',
};

function esc(text: string): string {
  return text.replace(/\|/g, '\\|');
}

function findingId(index: number): string {
  return `F-${String(index + 1).padStart(2, '0')}`;
}

export function renderMarkdown(result: AuditResult): string {
  const counts = countBySeverity(result.findings);
  const lines: string[] = [];

  lines.push('# Supabase Security Audit Report', '');
  lines.push(`- **Generated by:** ${result.tool.name} v${result.tool.version}`);
  if (result.target.url) lines.push(`- **Project URL:** ${result.target.url}`);
  if (result.target.repo) lines.push(`- **Repository scanned:** \`${result.target.repo}\``);
  lines.push(`- **Date:** ${result.finishedAt || result.startedAt}`);
  lines.push('- **Mode:** read-only (GET requests with the public anon key; no data was created, modified or deleted)', '');

  lines.push('## Summary', '');
  lines.push('| Severity | Count |', '|---|---:|');
  for (const s of SEVERITIES) lines.push(`| ${SEVERITY_LABEL[s]} | ${counts[s]} |`);
  lines.push('');

  if (counts.critical > 0) {
    lines.push(`> **Action needed:** ${counts.critical} critical issue(s) mean that private data or full control of the project is reachable by anyone today. Fix those first.`, '');
  } else if (result.findings.length === 0) {
    lines.push('> No issues were detected by the automated checks. See *Limitations* for what still needs a manual review.', '');
  }

  if (result.findings.length > 0) {
    lines.push('| ID | Severity | Area | Finding |', '|---|---|---|---|');
    result.findings.forEach((f, i) => {
      lines.push(`| ${findingId(i)} | ${SEVERITY_LABEL[f.severity]} | ${CATEGORY_LABEL[f.category]} | ${esc(f.title)} |`);
    });
    lines.push('');
  }

  const inv = result.inventory;
  if (result.target.url || result.target.repo) {
    lines.push('## What was checked', '');
    if (result.target.url) {
      lines.push(`- Tables / views probed: ${inv.tables.length ? inv.tables.map((t) => `\`${t}\``).join(', ') : 'none discovered'}`);
      lines.push(`- RPC functions listed (not executed): ${inv.rpcFunctions.length ? inv.rpcFunctions.map((t) => `\`${t}\``).join(', ') : 'none'}`);
      lines.push(`- Storage buckets visible: ${inv.buckets.length ? inv.buckets.map((t) => `\`${t}\``).join(', ') : 'none'}`);
      lines.push('- Auth settings: `/auth/v1/settings`');
    }
    if (result.target.repo) lines.push(`- Source files scanned for secrets: ${inv.filesScanned}`);
    lines.push('');
  }

  if (result.findings.length > 0) {
    lines.push('## Findings', '');
    result.findings.forEach((f, i) => {
      lines.push(`### ${findingId(i)} [${SEVERITY_LABEL[f.severity]}] ${f.title}`, '');
      lines.push(`*Area:* ${CATEGORY_LABEL[f.category]} &middot; *Check:* \`${f.checkId}\``, '');
      lines.push('**What this means**', '', f.description, '');
      lines.push('**Evidence**', '');
      for (const e of f.evidence) lines.push(`- ${e}`);
      lines.push('');
      lines.push('**Business impact**', '', f.impact, '');
      lines.push('**Recommended fix**', '', f.fix, '');
      if (f.references?.length) {
        lines.push('**References**', '');
        for (const r of f.references) lines.push(`- ${r}`);
        lines.push('');
      }
    });
  }

  if (result.passed.length > 0) {
    lines.push('## Checks that passed', '');
    for (const p of result.passed) lines.push(`- **${p.title}** (${CATEGORY_LABEL[p.category]}): ${p.detail}`);
    lines.push('');
  }

  lines.push('## Limitations', '');
  lines.push('This is an automated, outside-in, read-only check. It is a strong first signal, not a complete audit.', '');
  for (const l of result.limitations) lines.push(`- ${l}`);
  lines.push('');
  lines.push('---', '', '*Only run this tool against projects you own or are explicitly authorised to test.*', '');
  return lines.join('\n');
}
